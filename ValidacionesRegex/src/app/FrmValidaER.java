    private void btnValidarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidarActionPerformed
        // TODO add your handling code here:
        this.resetearColores();
        String patron= this.txtPatron.getText();
        ExpresionRegular exp= new ExpresionRegular(patron);
        
        String texto= this.txtTexto.getText();
        if (exp.esValido(texto)){
            this.txtTexto.setBackground(Color.green);
        }
        else{
            this.txtTexto.setForeground(Color.white);
            this.txtTexto.setBackground(Color.red);            
        }
    }//GEN-LAST:event_btnValidarActionPerformed

